-- En pgAdmin, abre Query Tool sobre la base assistia.
-- Puedes ejecutar el archivo como assistia_local o como administrador.
BEGIN;

SET LOCAL ROLE assistia_local;

CREATE TABLE IF NOT EXISTS public.pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    telefono VARCHAR(25)
);

CREATE TABLE IF NOT EXISTS public.cuidadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    telefono VARCHAR(25),
    correo VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS public.medico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    especialidad VARCHAR(80) NOT NULL,
    telefono VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS public.medicamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    principio_activo VARCHAR(120) NOT NULL,
    presentacion VARCHAR(60) NOT NULL,
    concentracion VARCHAR(60) NOT NULL,
    CONSTRAINT uk_medicamento_producto UNIQUE (nombre, presentacion, concentracion)
);

CREATE TABLE IF NOT EXISTS public.asignaciones_cuidador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    cuidador_id BIGINT NOT NULL,
    parentesco VARCHAR(60),
    responsable_principal BOOLEAN NOT NULL,
    CONSTRAINT fk_asignacion_paciente FOREIGN KEY (paciente_id) REFERENCES public.pacientes (id),
    CONSTRAINT fk_asignacion_cuidador FOREIGN KEY (cuidador_id) REFERENCES public.cuidadores (id),
    CONSTRAINT uq_asignacion_paciente_cuidador UNIQUE (paciente_id, cuidador_id)
);

CREATE INDEX IF NOT EXISTS idx_asignacion_cuidador
    ON public.asignaciones_cuidador (cuidador_id);

COMMIT;
