-- En pgAdmin, abre Query Tool sobre la base assistia con el usuario de DB_USER.
-- En una base existente, ese usuario debe poder crear tablas y gestionar sus índices.
BEGIN;

CREATE TABLE IF NOT EXISTS public.pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    telefono VARCHAR(25)
);

CREATE TABLE IF NOT EXISTS public.cuidadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    telefono VARCHAR(25),
    correo VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS public.medico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    especialidad VARCHAR(80) NOT NULL,
    telefono VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS public.medicamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    principio_activo VARCHAR(120) NOT NULL,
    presentacion VARCHAR(60) NOT NULL,
    concentracion VARCHAR(60) NOT NULL,
    CONSTRAINT uk_medicamento_producto UNIQUE (nombre, presentacion, concentracion)
);

CREATE TABLE IF NOT EXISTS public.asignaciones_cuidador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    cuidador_id BIGINT NOT NULL,
    parentesco VARCHAR(60),
    responsable_principal BOOLEAN NOT NULL,
    CONSTRAINT fk_asignacion_paciente FOREIGN KEY (paciente_id) REFERENCES public.pacientes (id),
    CONSTRAINT fk_asignacion_cuidador FOREIGN KEY (cuidador_id) REFERENCES public.cuidadores (id),
    CONSTRAINT uq_asignacion_paciente_cuidador UNIQUE (paciente_id, cuidador_id)
);

CREATE INDEX IF NOT EXISTS idx_asignacion_cuidador
    ON public.asignaciones_cuidador (cuidador_id);

CREATE TABLE IF NOT EXISTS public.tratamientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    medico_id BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    activo BOOLEAN NOT NULL,
    CONSTRAINT fk_tratamiento_paciente FOREIGN KEY (paciente_id) REFERENCES public.pacientes (id),
    CONSTRAINT fk_tratamiento_medico FOREIGN KEY (medico_id) REFERENCES public.medico (id)
);

CREATE TABLE IF NOT EXISTS public.detalles_tratamiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tratamiento_id BIGINT NOT NULL,
    medicamento_id BIGINT NOT NULL,
    dosis_indicada NUMERIC(12, 3) NOT NULL,
    unidad VARCHAR(30) NOT NULL,
    instrucciones VARCHAR(500),
    CONSTRAINT fk_detalle_tratamiento FOREIGN KEY (tratamiento_id) REFERENCES public.tratamientos (id),
    CONSTRAINT fk_detalle_medicamento FOREIGN KEY (medicamento_id) REFERENCES public.medicamento (id)
);

CREATE INDEX IF NOT EXISTS idx_tratamiento_paciente ON public.tratamientos (paciente_id);
CREATE INDEX IF NOT EXISTS idx_detalle_tratamiento ON public.detalles_tratamiento (tratamiento_id);

CREATE TABLE IF NOT EXISTS public.registro_toma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle_tratamiento_id BIGINT NOT NULL,
    fecha_hora_programada TIMESTAMP NOT NULL,
    fecha_hora_real TIMESTAMP,
    estado VARCHAR(20) NOT NULL,
    observacion VARCHAR(300),
    CONSTRAINT fk_registro_toma_detalle FOREIGN KEY (detalle_tratamiento_id)
        REFERENCES public.detalles_tratamiento (id),
    CONSTRAINT uq_registro_toma_detalle_hora UNIQUE (detalle_tratamiento_id, fecha_hora_programada),
    CONSTRAINT ck_registro_toma_estado_hora CHECK (
        (estado = 'PENDIENTE' AND fecha_hora_real IS NULL)
        OR (estado = 'REALIZADA' AND fecha_hora_real IS NOT NULL)
    )
);

COMMIT;
