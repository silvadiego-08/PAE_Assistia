DROP TABLE IF EXISTS registro_toma CASCADE;
DROP TABLE IF EXISTS detalle_tratamiento CASCADE;
DROP TABLE IF EXISTS tratamiento CASCADE;
DROP TABLE IF EXISTS medicamento CASCADE;
DROP TABLE IF EXISTS paciente CASCADE;

CREATE TABLE paciente (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres varchar(100) NOT NULL,
    apellidos varchar(100) NOT NULL,
    cedula varchar(20) NOT NULL UNIQUE
);

CREATE TABLE medicamento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL,
    presentacion varchar(80),
    concentracion varchar(80)
);

CREATE TABLE tratamiento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id bigint NOT NULL,
    descripcion varchar(200) NOT NULL,
    fecha_inicio date,
    fecha_fin date,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT fk_tratamiento_paciente
        FOREIGN KEY (paciente_id) REFERENCES paciente(id)
);

CREATE TABLE detalle_tratamiento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tratamiento_id bigint NOT NULL,
    medicamento_id bigint NOT NULL,
    dosis varchar(100),
    frecuencia_horas integer,
    indicaciones varchar(300),
    CONSTRAINT fk_detalle_tratamiento
        FOREIGN KEY (tratamiento_id) REFERENCES tratamiento(id),
    CONSTRAINT fk_detalle_medicamento
        FOREIGN KEY (medicamento_id) REFERENCES medicamento(id)
);

CREATE TABLE registro_toma (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle_tratamiento_id bigint NOT NULL,
    fecha_hora_programada timestamp NOT NULL,
    fecha_hora_real timestamp,
    estado varchar(20) NOT NULL,
    observacion varchar(300),
    CONSTRAINT fk_registro_toma_detalle
        FOREIGN KEY (detalle_tratamiento_id) REFERENCES detalle_tratamiento(id),
    CONSTRAINT ck_registro_toma_estado
        CHECK (estado IN ('PENDIENTE', 'REALIZADA')),
    CONSTRAINT uq_registro_toma_detalle_hora
        UNIQUE (detalle_tratamiento_id, fecha_hora_programada)
);

CREATE INDEX ix_registro_toma_pendientes
    ON registro_toma (estado, fecha_hora_programada);
